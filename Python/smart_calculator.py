'''
A program for calculating addition, subtraction, multiplication, division, floor division, remainder, and power
'''


n1 = int(input("Enter your first number: "))
n2 = int(input("Enter your second number: "))

print(f"Sum of {n1} + {n2} = {n1+n2}")
print(f"Difference of {n1} - {n2} = {n1-n2}")
print(f"Product of {n1} x {n2} = {n1*n2}")
print(f"Division of {n1} / {n2} = {n1/n2}")
print(f"Floor Division of {n1} // {n2} = {n1//n2}")
print(f"Remainder {n1} % {n2} = {n1%n2}")
print(f"Power of {n1} ** {n2} = {n1**n2}")